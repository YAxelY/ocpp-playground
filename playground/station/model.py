"""The simulated station's hardware model: EVSEs, transactions and its device-model variables."""
from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field


@dataclass
class TxState:
    id: str = field(default_factory=lambda: uuid.uuid4().hex[:16])   # generated by the station (Part 0 §2.8.2)
    seq: int = -1                     # last seqNo used; the first event gets 0
    token: str | None = None
    charging: bool = False
    energy_wh: float = 0.0
    remote_start_id: int | None = None
    started: float = field(default_factory=time.time)

    def next_seq(self) -> int:
        self.seq += 1
        return self.seq


@dataclass
class Evse:
    id: int
    status: str = "Available"         # ConnectorStatusEnumType (one connector per EVSE here)
    operative: bool = True
    cable: bool = False
    fault: bool = False
    tx: TxState | None = None
    changed_while_offline: bool = False
    pending_operative: bool | None = None    # ChangeAvailability "Scheduled" until the transaction ends

    def computed_status(self) -> str:
        if self.fault:
            return "Faulted"
        if not self.operative:
            return "Unavailable"
        return "Occupied" if self.cable else "Available"


# Device model: "Component.Variable" -> [value, mutability]. A small subset of the standardised
# components/variables (Part 2 Appendices), enough for Get/SetVariables and GetBaseReport.
def default_variables(heartbeat: int = 10) -> dict:
    return {
        "OCPPCommCtrlr.HeartbeatInterval": [heartbeat, "ReadWrite"],
        "OCPPCommCtrlr.OfflineThreshold": [20, "ReadWrite"],
        "OCPPCommCtrlr.RetryBackOffWaitMinimum": [2, "ReadWrite"],
        "OCPPCommCtrlr.RetryBackOffRandomRange": [2, "ReadWrite"],
        "OCPPCommCtrlr.RetryBackOffRepeatTimes": [3, "ReadWrite"],
        "SampledDataCtrlr.TxUpdatedInterval": [5, "ReadWrite"],
        "TxCtrlr.TxStartPoint": ["EVConnected,Authorized", "ReadOnly"],
        "TxCtrlr.TxStopPoint": ["EVConnected,Authorized", "ReadOnly"],
        "ChargingStation.Model": ["Playground-1", "ReadOnly"],
        "ChargingStation.VendorName": ["OCPP Playground", "ReadOnly"],
    }
