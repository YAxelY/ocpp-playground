"""Generate docs/ocpp-versions-compared.md from the JSON schemas of OCPP 1.6, 2.0.1 and 2.1.

    python -m playground.tools.schema_report > docs/ocpp-versions-compared.md
"""
from __future__ import annotations

from collections import Counter

from ..protocol import schemas
from ..protocol.versions import BY_NAME

FOCUS = [("BootNotification", "request"), ("BootNotification", "response"), ("Heartbeat", "request"),
         ("StatusNotification", "request"), ("Authorize", "request"), ("Authorize", "response"),
         ("TransactionEvent", "request"), ("StartTransaction", "request"), ("StopTransaction", "request"),
         ("MeterValues", "request"), ("RequestStartTransaction", "request"), ("RemoteStartTransaction", "request")]


def fmt(f: dict | None) -> str:
    if not f:
        return "—"
    bits = [f["type"] or "?"]
    if f["required"]:
        bits.append("**required**")
    if f["maxLength"]:
        bits.append(f"≤{f['maxLength']}")
    if f["enum"]:
        bits.append(f"{len(f['enum'])} values")
    return " · ".join(bits)


def section(action: str, kind: str, a: str, b: str) -> list[str]:
    c = schemas.compare(action, kind, BY_NAME[a], BY_NAME[b])
    out = [f"#### {action} ({kind}): {a} → {b}", ""]
    if c["replaced"]:
        out += [f"🔁 {c['replaced']}", ""]
    if c["status"] == "same":
        return out + ["No structural change.", ""]
    if c["status"].startswith("only") or c["status"] == "absent":
        return out + [f"{c['status']}.", ""]
    out += ["| field | " + a + " | " + b + " |", "|---|---|---|"]
    for r in c["rows"]:
        if r["change"] != "same":
            out.append(f"| `{r['path']}` | {fmt(r['a'])} | {fmt(r['b'])} |")
    return out + [""]


def main() -> None:
    cat = schemas.catalogue()
    lines = [
        "# OCPP 1.6, 2.0.1 and 2.1 compared (message schemas)",
        "",
        "_Generated by `python -m playground.tools.schema_report`. Structural comparison of the JSON schemas:_",
        "_fields, required flags, types, maximum lengths, formats and allowed values. Behaviour changes live in the_",
        "_specification text, see [conformance.md](conformance.md). Schema source: "
        + ", ".join(f"{v} {s}" for v, s in cat["sources"].items())
        + " ([provenance](schema-provenance.md))._",
        "",
        "## Summary",
        "",
        "| | same | changed | replaced | only in the older | only in the newer |",
        "|---|---|---|---|---|---|",
    ]
    for pair in cat["pairs"]:
        a, b = pair.split("|")
        c = Counter(i["status"][pair] for i in cat["items"])
        lines.append(f"| {a} → {b} | {c['same']} | {c['changed']} | {c['renamed']} | {c['only ' + a]} | {c['only ' + b]} |")
    lines += [
        "",
        "_Counted per schema file (a request and its response count separately). \"Replaced\" = a 1.6 message whose role",
        "moved to a differently named 2.x message (see the table below)._",
        "",
        "## RPC framework (OCPP-J)",
        "",
        "| | 1.6 | 2.0.1 | 2.1 |",
        "|---|---|---|---|",
        "| WebSocket subprotocol | `ocpp1.6` | `ocpp2.0.1` | `ocpp2.1` |",
        "| Message types | 2 · 3 · 4 | 2 · 3 · 4 | 2 · 3 · 4 · **5 CALLRESULTERROR** · **6 SEND** |",
        "| Unknown MessageTypeId | ignore the payload (J §4.1.3) | CALLERROR `MessageTypeNotSupported` (§4.4) | ignore the payload (§4.4) |",
        "| Unreadable message id | not specified | CALLERROR with id `\"-1\"` (§4.2.3) | same as 2.0.1 |",
        "| Message-id uniqueness | per WebSocket connection (J §4.1.4) | per station identity, all connections (§4.1.4) | same as 2.0.1 |",
        "| Schema file names | `Action.json` / `ActionResponse.json` | `ActionRequest.json` / `ActionResponse.json` | + `Action.json` for SEND |",
        "| Error codes | `FormationViolation`, `OccurenceConstraintViolation` (sic), no RpcFrameworkError / MessageTypeNotSupported | `FormatViolation`, `OccurrenceConstraintViolation`, `RpcFrameworkError`, `MessageTypeNotSupported` | same as 2.0.1 |",
        "",
        "## 1.6 messages replaced in 2.x",
        "",
        "| 1.6 | 2.x | source |",
        "|---|---|---|",
    ]
    for old, (news, why) in schemas.REPLACED_IN_2X.items():
        lines.append(f"| `{old}` | {', '.join('`' + n + '`' for n in news)} | {why} |")
    lines += ["", "## The messages the playground uses", ""]
    for action, kind in FOCUS:
        lines += section(action, kind, "1.6", "2.0.1")
        lines += section(action, kind, "2.0.1", "2.1")
    for a, b in (("2.0.1", "2.1"),):
        new = sorted({i["action"] for i in cat["items"] if i["status"][f"{a}|{b}"] == f"only {b}"})
        lines += [f"## New in {b} (compared with {a})", "", ", ".join(f"`{n}`" for n in new), ""]
    ext = sorted(schemas.SECURITY_EXTENSION_16)
    lines += ["## 1.6 security extension", "",
              "The `ocpp` library also ships these 1.6 messages from the later *OCPP 1.6 security* white paper. They are",
              "**not** in the OCPP 1.6 Edition 2 schema set: " + ", ".join(f"`{n}`" for n in ext) + ".", ""]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
