"""Generate docs/ocpp-2.0.1-vs-2.1.md from the official JSON schemas.

    python -m playground.tools.schema_report > docs/ocpp-2.0.1-vs-2.1.md
"""
from __future__ import annotations

import os

from ..protocol import V21, V201, schemas

FOCUS = ["BootNotification", "Heartbeat", "StatusNotification", "Authorize", "TransactionEvent",
         "GetVariables", "SetVariables", "RequestStartTransaction", "TriggerMessage", "Reset"]


def section(d: dict) -> list[str]:
    out = []
    if d["only_in"]:
        return [f"- only in OCPP {d['only_in']}"]
    if schemas.is_unchanged(d):
        return ["- no structural change (same fields, required flags, types and enum values)"]
    for f in d["added"]:
        out.append(f"- **added** `{f}`")
    for f in d["removed"]:
        out.append(f"- **removed** `{f}`")
    for c in d["required_changed"]:
        out.append(f"- `{c['field']}`: {'required' if c['from'] else 'optional'} → {'required' if c['to'] else 'optional'}")
    for c in d["type_changed"]:
        out.append(f"- `{c['field']}`: type {c['from']} → {c['to']}")
    for e in d["enum_added"]:
        out.append(f"- `{e['field']}`: new values {', '.join('`' + v + '`' for v in e['values'])}")
    for e in d["enum_removed"]:
        out.append(f"- `{e['field']}`: values removed {', '.join('`' + v + '`' for v in e['values'])}")
    return out


def main() -> None:
    a, b = schemas.store(V201), schemas.store(V21)
    names = sorted(set(f[:-5] for f in os.listdir(a.dir) if f.endswith(".json")) |
                   set(f[:-5] for f in os.listdir(b.dir) if f.endswith(".json")))
    diffs = {n: schemas.diff(a, b, n) for n in names}
    same = [n for n, d in diffs.items() if schemas.is_unchanged(d)]
    changed = [n for n, d in diffs.items() if not d["only_in"] and not schemas.is_unchanged(d)]
    only21 = [n for n, d in diffs.items() if d["only_in"] == "2.1"]
    only201 = [n for n, d in diffs.items() if d["only_in"] == "2.0.1"]

    lines = [
        "# OCPP 2.0.1 vs 2.1: message schemas",
        "",
        "_Generated by `python -m playground.tools.schema_report` from the official JSON schemas shipped with the",
        "[`ocpp`](https://pypi.org/project/ocpp/) library. Structural comparison only: fields, required flags, types",
        "and enum values. Normative behaviour changes live in the specification text, not in the schemas._",
        "",
        "| | count |",
        "|---|---|",
        f"| schemas identical in both versions | {len(same)} |",
        f"| schemas changed in 2.1 | {len(changed)} |",
        f"| schemas only in 2.1 | {len(only21)} |",
        f"| schemas only in 2.0.1 | {len(only201)} |",
        "",
        "## RPC framework (OCPP-J, Part 4)",
        "",
        "| | 2.0.1 | 2.1 |",
        "|---|---|---|",
        "| WebSocket subprotocol | `ocpp2.0.1` | `ocpp2.1` |",
        "| Message types | 2 CALL · 3 CALLRESULT · 4 CALLERROR | + **5 CALLRESULTERROR** · **6 SEND** |",
        "| Unknown MessageTypeId | answer CALLERROR `MessageTypeNotSupported` (§4.4) | ignore the payload (§4.4) |",
        "| Unconfirmed messages | — | SEND: never answered, may be sent while a CALL is open |",
        "",
        "## The messages this playground uses",
        "",
    ]
    for action in FOCUS:
        for kind in ("Request", "Response"):
            name = action + kind
            lines += [f"### {name}", "", *section(diffs[name]), ""]
    lines += ["## New in 2.1 (requests, responses and SEND messages)", "",
              ", ".join(f"`{n}`" for n in only21), "", "## Changed in 2.1 (all)", ""]
    for n in changed:
        d = diffs[n]
        bits = []
        if d["added"]:
            bits.append(f"+{len(d['added'])} field(s)")
        if d["removed"]:
            bits.append(f"−{len(d['removed'])} field(s)")
        if d["required_changed"]:
            bits.append("required flags")
        if d["enum_added"] or d["enum_removed"]:
            bits.append("enum values")
        if d["type_changed"]:
            bits.append("types")
        lines.append(f"- `{n}`: {', '.join(bits)}")
    lines += ["", "## Identical in both versions", "", ", ".join(f"`{n}`" for n in same), ""]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
